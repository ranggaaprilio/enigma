"""Pure `.env` file parsing and serialisation -- no I/O, no decryption, no sandbox access.

This module only knows about text in, text out. `app.services.workspace_env` is what actually
decrypts workspace env vars and writes the serialised result into a sandbox.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

# Case is preserved here; uppercasing/normalisation is `app.services.workspaces.validate_env_key`'s
# job, applied when a key is written, not when a `.env` file is parsed back.
_KEY_PATTERN = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
# Characters `serialize_env` will write without quoting at all.
_BARE_VALUE_PATTERN = re.compile(r"^[A-Za-z0-9_./:@+,=%-]*$")

_HEADER = (
    "# Generated by Enigma from workspace environment variables. Do not edit by hand -- "
    "rewritten on every service start. Do not commit.\n"
)


@dataclass(frozen=True)
class ParsedLine:
    key: str
    value: str
    line_no: int


@dataclass(frozen=True)
class ParseProblem:
    """A line that could not be parsed as `KEY=value`, or a duplicate-key notice.

    `message` is always a generic description of the problem -- it never includes the raw
    value, so a problem list is safe to log or display without leaking a secret.
    """

    line_no: int
    message: str


def parse_env_text(text: str) -> tuple[list[ParsedLine], list[ParseProblem]]:
    """Parse `.env`-style text into `(lines, problems)`.

    Grammar:
    * `\\r\\n` is normalised to `\\n` and a leading BOM is stripped.
    * Blank lines and lines whose first non-whitespace character is `#` are ignored.
    * An optional `export ` prefix (the literal word `export` plus whitespace) is stripped
      before the key is parsed.
    * A key must match `^[A-Za-z_][A-Za-z0-9_]*$`. A line with no `=`, or whose key does not
      match, produces a `ParseProblem` and is skipped -- it never aborts the rest of the parse.
    * After an optional space around `=`, the value is single-quoted (`'...'`, literal, no
      escapes, must close on the same physical line), double-quoted (`"..."`, may span multiple
      physical lines until an unescaped `"`, recognising `\\n` `\\r` `\\t` `\\"` `\\\\`), or
      unquoted (runs to end of line, trailing whitespace trimmed; an inline comment is only
      recognised when the `#` is preceded by whitespace -- `abc#123` stays part of the value).
      No shell-style variable interpolation is ever performed, in any form.

    Duplicate keys: a later occurrence overwrites an earlier one, so the returned `ParsedLine`
    list has exactly one entry per distinct key (its *last* occurrence's value and line number).
    When a key appears more than once, an extra `ParseProblem` is emitted at the last
    occurrence's line, of the form `"KEY appears N times; last value used"`, so a caller can
    still surface that as a warning without needing to reduce the list itself.
    """
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    if normalized.startswith("﻿"):
        normalized = normalized[1:]
    physical_lines = normalized.split("\n")

    problems: list[ParseProblem] = []
    order: list[str] = []
    values: dict[str, str] = {}
    line_nos: dict[str, int] = {}
    counts: dict[str, int] = {}

    index = 0
    total = len(physical_lines)
    while index < total:
        raw_line = physical_lines[index]
        line_no = index + 1
        stripped = raw_line.strip()
        if not stripped or stripped.startswith("#"):
            index += 1
            continue

        content = raw_line.lstrip(" \t")
        if content == "export":
            content = ""
        elif content.startswith("export ") or content.startswith("export\t"):
            content = content[len("export") :].lstrip(" \t")

        eq_index = content.find("=")
        if eq_index == -1:
            problems.append(ParseProblem(line_no, "expected KEY=value"))
            index += 1
            continue

        key_part = content[:eq_index].rstrip(" \t")
        if not _KEY_PATTERN.fullmatch(key_part):
            problems.append(ParseProblem(line_no, "invalid key"))
            index += 1
            continue

        raw_after_eq = content[eq_index + 1 :]
        lstripped = raw_after_eq.lstrip(" \t")

        if lstripped.startswith("'"):
            closing = lstripped.find("'", 1)
            if closing == -1:
                problems.append(ParseProblem(line_no, "unterminated quoted value"))
                index += 1
                continue
            value = lstripped[1:closing]
            _record(order, values, line_nos, counts, key_part, value, line_no)
            index += 1
            continue

        if lstripped.startswith('"'):
            tail = "\n".join([lstripped[1:], *physical_lines[index + 1 :]])
            value, end_index, closed = _decode_double_quoted(tail)
            if not closed:
                problems.append(ParseProblem(line_no, "unterminated quoted value"))
                break
            consumed_newlines = tail[:end_index].count("\n")
            _record(order, values, line_nos, counts, key_part, value, line_no)
            index += 1 + consumed_newlines
            continue

        value = _parse_unquoted(raw_after_eq)
        _record(order, values, line_nos, counts, key_part, value, line_no)
        index += 1

    for key in order:
        if counts[key] > 1:
            problems.append(
                ParseProblem(line_nos[key], f"{key} appears {counts[key]} times; last value used")
            )

    parsed = [ParsedLine(key=key, value=values[key], line_no=line_nos[key]) for key in order]
    return parsed, problems


def _record(
    order: list[str],
    values: dict[str, str],
    line_nos: dict[str, int],
    counts: dict[str, int],
    key: str,
    value: str,
    line_no: int,
) -> None:
    if key in values:
        counts[key] += 1
    else:
        order.append(key)
        counts[key] = 1
    values[key] = value
    line_nos[key] = line_no


def _decode_double_quoted(tail: str) -> tuple[str, int, bool]:
    """`tail` starts right after the opening `"`, across joined subsequent physical lines
    (joined with `\\n`, matching the already-normalised line endings). Returns
    `(value, end_index, closed)` where `end_index` is the offset in `tail` just past the
    closing quote (or `len(tail)` when unterminated)."""
    chars: list[str] = []
    index = 0
    length = len(tail)
    while index < length:
        char = tail[index]
        if char == "\\" and index + 1 < length:
            nxt = tail[index + 1]
            if nxt == "n":
                chars.append("\n")
            elif nxt == "r":
                chars.append("\r")
            elif nxt == "t":
                chars.append("\t")
            elif nxt == '"':
                chars.append('"')
            elif nxt == "\\":
                chars.append("\\")
            else:
                chars.append("\\")
                chars.append(nxt)
            index += 2
            continue
        if char == '"':
            return "".join(chars), index + 1, True
        chars.append(char)
        index += 1
    return "".join(chars), length, False


def _parse_unquoted(raw_after_eq: str) -> str:
    """`raw_after_eq` is the untouched text after `=` (leading/trailing whitespace intact) so
    an inline comment can be told apart from a `#` glued to the value: a comment only starts at
    a `#` immediately preceded by whitespace."""
    cut = len(raw_after_eq)
    for index in range(len(raw_after_eq)):
        if raw_after_eq[index] == "#" and index > 0 and raw_after_eq[index - 1] in (" ", "\t"):
            cut = index
            break
    return raw_after_eq[:cut].strip(" \t")


def serialize_env(values: dict[str, str]) -> str:
    """Render `values` as `.env` text: sorted by key, one `KEY=value` line each, prefixed with
    a do-not-edit header. Round-trips through `parse_env_text` for any value, including ones
    containing spaces, quotes, newlines, or `$` (never interpolated)."""
    body_lines = [f"{key}={_format_value(values[key])}" for key in sorted(values)]
    return _HEADER + "\n".join(body_lines) + ("\n" if body_lines else "")


def _format_value(value: str) -> str:
    if _BARE_VALUE_PATTERN.fullmatch(value):
        return value
    if "'" not in value and "\n" not in value:
        return f"'{value}'"
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'
